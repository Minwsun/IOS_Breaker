"""Generate app-scoped RevenueCat modules without guessed entitlement/product IDs."""
import argparse
import json
from pathlib import Path
import re
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
PATTERN = r"^https:\/\/api\.(revenuecat|rc-backup)\.com\/v1\/(receipts|subscribers\/[^/?#]+)\/?(\?[^#]*)?$"


def build(ref="codex/self-hosted-app-expansion"):
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_./-]*", ref) or ".." in ref:
        raise ValueError("Invalid Git ref")
    profiles = json.loads((ROOT / "config/revenuecat-apps.json").read_text(encoding="utf-8"))["apps"]
    base = "https://raw.githubusercontent.com/Minwsun/IOS_Breaker/refs/heads/" + ref
    output = {}
    for profile in profiles + [{"slug": "Dynamic", "name": "All RevenueCat apps", "user_agent_tokens": []}]:
        if not re.fullmatch(r"[A-Za-z0-9-]+", profile["slug"]) or not re.fullmatch(r"[A-Za-z0-9 +.-]+", profile["name"]):
            raise ValueError("Invalid profile name")
        tokens = profile["user_agent_tokens"]
        if any(not re.fullmatch(r"[A-Za-z0-9 +./-]+", token) for token in tokens):
            raise ValueError("Invalid app selector")
        argument = ",argument=ua=" + quote("|".join(tokens), safe="") if tokens else ""
        script_name = "rc-" + profile["slug"].lower()
        content = (
            "#!name=" + profile["name"] + " - RevenueCat experimental\n"
            "#!desc=Mapping discovery; fixture-tested only. Signed responses pass through. Never combine with another RevenueCat processor.\n"
            "# Generated by scripts/build_premium_modules.py from config/revenuecat-apps.json.\n"
            "# App selection is based on legacy User-Agent evidence; current app behavior is unverified.\n"
            "[Script]\n"
            + script_name + "-request = type=http-request,pattern=" + PATTERN + ",script-path=" + base + "/js/revenuecat-compatible.js,timeout=10" + argument + "\n"
            + script_name + "-response = type=http-response,pattern=" + PATTERN + ",requires-body=true,max-size=1048576,script-path=" + base + "/js/revenuecat-compatible.js,timeout=10" + argument + "\n"
            "[MITM]\nhostname = %APPEND%, api.revenuecat.com, api.rc-backup.com\n"
        )
        name = "modules/RevenueCat-" + profile["slug"] + ".sgmodule"
        if name in output:
            raise ValueError("Duplicate app slug")
        output[name] = content
    output["modules/Locket.sgmodule"] = "# Alias retained for existing Locket download URLs.\n" + output["modules/RevenueCat-Locket.sgmodule"]
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ref", default="codex/self-hosted-app-expansion")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = build(args.ref)
    for name, content in outputs.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit("Regenerate " + name)
        else:
            path.write_bytes(content.encode("utf-8"))
    print(("Checked " if args.check else "Generated ") + str(len(outputs)) + " app-scoped/shared RevenueCat modules")


if __name__ == "__main__":
    main()
